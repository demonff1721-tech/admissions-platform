"""Pydantic data models for structured output, scoring, and workflow entities."""

from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field


class ExtractedFields(BaseModel):
    """Structured extraction validated schema from incoming student messages."""
    programme_interest: Optional[str] = Field(default=None, description="Specific programme e.g. MBA, B.Tech CSE, BBA LLB, or broad discipline")
    education: Optional[str] = Field(default=None, description="Highest qualification e.g. B.Tech graduate, B.Com final year, 12th standard")
    work_experience: Optional[str] = Field(default=None, description="Years or domain of experience e.g. 2 years IT, Fresher")
    intended_intake: Optional[str] = Field(default=None, description="Intended intake e.g. 2026 upcoming, 2027, undecided")
    application_readiness: Optional[str] = Field(default=None, description="Ready to apply, awaiting results, exploratory")
    primary_concern: Optional[str] = Field(default=None, description="fees, eligibility, placements, application process, syllabus, etc.")
    wants_counsellor: Optional[bool] = Field(default=None, description="Whether student explicitly or implicitly requested counsellor call")
    message_type: str = Field(default="interest", description="factual_question, interest, complaint, stop, clarification_reply, objection")
    field_confidences: Dict[str, float] = Field(default_factory=dict, description="Confidence per extracted field from 0.0 to 1.0")
    overall_confidence: float = Field(default=0.90, description="Overall confidence score")
    missing_fields: List[str] = Field(default_factory=list, description="Crucial fields still missing from the lead profile")


class ScoreBreakdown(BaseModel):
    """Detailed deterministic scoring breakdown matching the 5-criterion rubric."""
    readiness_score: int = Field(ge=0, le=25, description="Criterion 1: Application Readiness (0, 5, 15, 25)")
    readiness_rationale: str
    
    intent_score: int = Field(ge=0, le=25, description="Criterion 2: Application Intent (0, 5, 15, 25)")
    intent_rationale: str
    
    fit_score: int = Field(ge=0, le=20, description="Criterion 3: Programme Fit (0, 10, 20)")
    fit_rationale: str
    
    eligibility_score: int = Field(ge=0, le=20, description="Criterion 4: Basic Eligibility (0, 10, 20)")
    eligibility_rationale: str
    
    engagement_score: int = Field(ge=0, le=10, description="Criterion 5: Engagement (0, 5, 10)")
    engagement_rationale: str
    
    total_score: int = Field(ge=0, le=100, description="Sum of 5 criteria, max 100")
    classification: str = Field(description="High, Medium, Low, or Uncertain")
    is_uncertain: bool = Field(default=False, description="Flag indicating mandatory escalation override")
    uncertain_reasons: List[str] = Field(default_factory=list, description="Reasons triggering Uncertain classification")


class CounsellorRecord(BaseModel):
    """Counsellor profile and roster state."""
    counsellor_id: str
    name: str
    specialisations: List[str]
    languages: List[str]
    active_high_leads: int = 0
    capacity: int = 8
    available_slots: List[str] = Field(default_factory=list)
    is_available: bool = True


class CounsellorProposal(BaseModel):
    """Proposed assignment generated by the Hungarian optimizer."""
    counsellor_id: str
    counsellor_name: str
    cost: float
    specialisation_match: bool
    language_match: bool
    current_load: int
    proposed_slot: str
    alternative_counsellors: List[Dict[str, Any]] = Field(default_factory=list)
    status: str = "Proposed"  # Proposed, Approved, Rejected, Waitlisted


class PolicyDecision(BaseModel):
    """Result of deterministic policy rule evaluation."""
    rule_id: str
    rule_name: str
    trigger_condition: str
    prior_state: str
    action_selected: str
    result_state: str
    autonomy_level: str  # Suggest, Approve, Act then report, Fully autonomous
    requires_approval: bool
    explanation: str


class LeadRecord(BaseModel):
    """Full lead entity representing a student enquiry."""
    lead_id: str
    created_at: str
    updated_at: str
    channel: str = "Web Chat"
    student_message: str
    name: str
    phone: Optional[str] = None
    email: Optional[str] = None
    consent_status: bool = True
    opt_out_status: bool = False
    programme_interest: Optional[str] = None
    education: Optional[str] = None
    work_experience: Optional[str] = None
    intended_intake: Optional[str] = None
    application_readiness: Optional[str] = None
    intent: Optional[str] = None
    extracted_fields_json: str = "{}"
    extraction_confidence: float = 1.0
    clarification_count: int = 0
    score_breakdown_json: str = "{}"
    total_score: int = 0
    eligibility_score: int = 0
    classification: str = "Uncertain"
    current_stage: str = "S1_Trigger"
    current_status: str = "New"
    escalation_flag: bool = False
    escalation_reason: Optional[str] = None
    assigned_counsellor: Optional[str] = None
    proposed_slot: Optional[str] = None
    approved_by: Optional[str] = None
    nurture_stage: Optional[str] = None
    nurture_messages_sent: int = 0
    last_contact_at: Optional[str] = None
    duplicate_of: Optional[str] = None
    case_summary: Optional[str] = None


class KnowledgeDoc(BaseModel):
    """Document in the verified institutional knowledge base."""
    doc_id: str
    title: str
    programme: str
    category: str
    approved_content: str
    official_source_url: str
    retrieval_metadata: Dict[str, Any] = Field(default_factory=dict)
    collection_date: str
    last_verified_date: str
    is_approved: bool = True


class TestCase(BaseModel):
    """Evaluation test case schema."""
    case_id: str
    category: str  # Normal High, Normal Medium, Normal Low, Exception, What-If, Failure Injection
    title: str
    input_message: str
    channel: str = "Web Chat"
    lead_profile: Dict[str, Any] = Field(default_factory=dict)
    expected_extracted_fields: Dict[str, Any] = Field(default_factory=dict)
    expected_score_breakdown: Dict[str, int] = Field(default_factory=dict)
    expected_classification: str
    expected_policy_rule: str
    expected_workflow_outcome: str
    expected_exception_handling: Optional[str] = None
    expected_approval_requirement: bool = False
